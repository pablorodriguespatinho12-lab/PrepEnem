def receita(*linhas):
  rotulos = ['1. Tabela do que eu tenho', '2. Equação em letras', '3. Achar cada letra', '4. Substituir']
  return list(zip(rotulos, linhas))


def calc(formulas, tenho, quer, equacao, porque, letras, telas, volta, valores, pista, rec, **extra):
  return dict(formulas=formulas, tenho=tenho, quer=quer, equacao=equacao, porque=porque, letras=letras,
              telas=[dict(titulo=t, texto=x) for t, x in telas], volta=volta, valores=valores, pista=pista,
              receita=receita(*rec), **extra)


def regra(formulas, tenho, quer, regra_txt, porque, letras, telas, volta, valores, pista, rec, **extra):
  """Questão sem conta: a regra pronta e uma tela por pista, como em Português."""
  rotulos = ['1. Separe as pistas', '2. A regra em palavras', '3. Ache cada pista', '4. Compare com as letras']
  return dict(titulo_formulas='A regra desta questão', formulas_texto='Esta é a regra que a questão usa. Já está pronta: é só usar.',
              formulas=formulas, tenho_texto='Primeiro, separe as pistas do enunciado.', tenho=tenho,
              titulo_regra='A regra em palavras', quer=quer, equacao=regra_txt, porque=porque, agora='Agora é só achar cada pista.',
              letras=letras, telas=[dict(titulo=t, texto=x) for t, x in telas], volta=volta, valores=valores, pista=pista,
              receita=list(zip(rotulos, rec)), **extra)


